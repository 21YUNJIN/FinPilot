# --- 用例 -----------------------------------------------------------------


def test_upgrade_head_creates_exact_model_table_set(engine, alembic_cfg):
    """空 schema + upgrade head 建出的表集合 == Base.metadata 表集合。"""
    _drop_schema(engine)
    assert _table_names(engine) == set(), "前置条件：schema 必须为空"

    command.upgrade(alembic_cfg, "head")

    created = _business_tables(engine)
    expected = set(Base.metadata.tables)
    assert len(expected) == EXPECTED_TABLE_COUNT, (
        f"models.py 表数量变化（{len(expected)} != {EXPECTED_TABLE_COUNT}）："
        "请在 models.py 变更后追加新的 Alembic 修订并更新 0001_initial.py 文件头"
    )
    assert created == expected, {
        "missing_in_migration": sorted(expected - created),
        "extra_in_migration": sorted(created - expected),
    }
    assert VERSION_TABLE in _table_names(engine), "缺少 alembic_version 版本表"


def test_upgrade_downgrade_upgrade_is_idempotent(engine, alembic_cfg):
    """upgrade → downgrade base → upgrade：回滚干净、再升级结果一致。"""
    _drop_schema(engine)

    command.upgrade(alembic_cfg, "head")
    first = _schema_signature(engine)
    assert set(first) - {VERSION_TABLE} == set(Base.metadata.tables)

    command.downgrade(alembic_cfg, "base")
    remaining = _table_names(engine)
    assert remaining == {VERSION_TABLE}, f"downgrade base 后仍残留业务表：{sorted(remaining - {VERSION_TABLE})}"

    command.upgrade(alembic_cfg, "head")
    second = _schema_signature(engine)
    assert second == first, "二次 upgrade 的表结构签名与首次不一致（迁移链不可重现）"


def test_alembic_check_and_compare_metadata_report_no_diff(engine, alembic_cfg):
    """关键断言：迁移链建出的库与 models.py **无差异**。"""
    _drop_schema(engine)
    command.upgrade(alembic_cfg, "head")

    # (1) CLI 语义的 Alembic 自检：有差异会抛 AutogenerateDiffsDetected
    command.check(alembic_cfg)

    # (2) 直接调用 compare_metadata，把差异清单打出来（便于失败时定位）
    from alembic.migration import MigrationContext

    with engine.connect() as conn:
        context = MigrationContext.configure(conn, opts={"compare_type": True})
        diffs = compare_metadata(context, Base.metadata)
    assert diffs == [], f"迁移链与 models.py 存在差异：{diffs}"


def test_alembic_check_detects_deliberate_drift(engine, alembic_cfg):
    """反向对照（防止断言空转）：人为制造漂移时 ``alembic check`` 必须报错。

    做法：在已迁移到 head 的库上删掉一张表，``command.check`` 应抛
    ``AutogenerateDiffsDetected``；随后 ``downgrade base + upgrade head`` 复原。
    没有这个用例，"无差异"断言可能是空转（例如 check 根本没连上库）。
    """
    _drop_schema(engine)
    command.upgrade(alembic_cfg, "head")

    with engine.begin() as conn:
        conn.execute(text("DROP TABLE merchant_quotes CASCADE"))

    with pytest.raises(AutogenerateDiffsDetected) as excinfo:
        command.check(alembic_cfg)
    assert "merchant_quotes" in str(excinfo.value)

    # 复原：整 schema 重建后 upgrade head。
    # 注意：这里刻意**不**用 `downgrade base` 复原——0001 的 downgrade 会显式
    # `op.drop_index('ix_merchant_quotes_merchant_id')`，而该索引已随 DROP TABLE CASCADE
    # 消失，会抛 UndefinedObject。这不是迁移缺陷（正常迁移的库上 downgrade 通过，见
    # test_upgrade_downgrade_upgrade_is_idempotent），而是"库被带外改坏后不能用 downgrade 修"
    # 的如实记录：PostgreSQL DDL 是事务性的，失败会整体回滚，不会留下半迁移状态。
    _drop_schema(engine)
    command.upgrade(alembic_cfg, "head")
    assert _business_tables(engine) == set(Base.metadata.tables)


def test_key_unique_constraints_exist(engine, alembic_cfg):
    """四个关键唯一约束存在（pg_constraint + SQLAlchemy 反射双重确认）。"""
    _drop_schema(engine)
    command.upgrade(alembic_cfg, "head")

    with engine.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT conname, conrelid::regclass::text AS tbl, contype "
                "FROM pg_constraint WHERE contype = 'u' AND conname = ANY(:names)"
            ),
            {"names": list(KEY_UNIQUE_CONSTRAINTS)},
        ).all()
    found = {row.conname: row.tbl for row in rows}

    for name, (table, columns) in KEY_UNIQUE_CONSTRAINTS.items():
        assert name in found, f"缺少唯一约束 {name}（表 {table}）"
        assert found[name].split(".")[-1].strip('"') == table, f"{name} 落在错误的表：{found[name]}"
        reflected = {
            tuple(sorted(uc["column_names"]))
            for uc in inspect(engine).get_unique_constraints(table, schema="public")
        }
        assert tuple(sorted(columns)) in reflected, (
            f"{table} 上的唯一约束列不匹配：期望 {columns}，反射结果 {sorted(reflected)}"
        )


def test_uq_daily_limit_bucket_is_enforced(engine, alembic_cfg):
    """唯一约束不只是"元数据存在"，而是在真实 PostgreSQL 上真的拦得住重复。"""
    _drop_schema(engine)
    command.upgrade(alembic_cfg, "head")

    with engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO users (user_id, status, display_name, phone_ref, email_ref, "
                "password_hash, totp_secret_enc, roles, created_at) "
                "VALUES ('user_mig_test', 'active', 'migration probe', '', '', '', '', '[]'::jsonb, now())"
            )
        )
        conn.execute(
            text(
                "INSERT INTO daily_limits (id, user_id, business_day, currency, "
                "settled_transfer_minor, held_pending_minor, version) "
                "VALUES ('dl_probe_1', 'user_mig_test', DATE '2026-10-27', 'CNY', 0, 0, 1)"
            )
        )

    with pytest.raises(IntegrityError) as excinfo:
        with engine.begin() as conn:
            conn.execute(
                text(
                    "INSERT INTO daily_limits (id, user_id, business_day, currency, "
                    "settled_transfer_minor, held_pending_minor, version) "
                    "VALUES ('dl_probe_2', 'user_mig_test', DATE '2026-10-27', 'CNY', 0, 0, 1)"
                )
            )
    assert "uq_daily_limit_bucket" in str(excinfo.value)


def test_cli_upgrade_head_matches_documented_command(engine, database_url):
    """文档里给的那条 CLI 命令必须原样可跑（子进程真实执行，不用 Python API 代替）。"""
    _drop_schema(engine)
    cmd = [
        sys.executable,
        "-m",
        "alembic",
        "-x",
        f"db_url={database_url}",
        "upgrade",
        "head",
    ]
    upgrade = subprocess.run(cmd, cwd=str(REPO_ROOT), capture_output=True, text=True, timeout=300)
    assert upgrade.returncode == 0, f"CLI upgrade 失败：\n{upgrade.stdout}\n{upgrade.stderr}"
    assert _business_tables(engine) == set(Base.metadata.tables)

    check = subprocess.run(
        [sys.executable, "-m", "alembic", "-x", f"db_url={database_url}", "check"],
        cwd=str(REPO_ROOT),
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert check.returncode == 0, f"alembic check 失败：\n{check.stdout}\n{check.stderr}"
    assert "No new upgrade operations detected." in check.stdout


def test_downgrade_base_removes_all_business_tables(engine, alembic_cfg):
    """显式单列的"回滚空库"断言（T22 备份演练与 CD 回滚都依赖它）。"""
    _drop_schema(engine)
    command.upgrade(alembic_cfg, "head")
    assert len(_business_tables(engine)) == EXPECTED_TABLE_COUNT

    command.downgrade(alembic_cfg, "base")
    assert _business_tables(engine) == set()
    with engine.connect() as conn:
        revision = conn.execute(
            text(f"SELECT version_num FROM {VERSION_TABLE}")
        ).scalar_one_or_none()
    assert revision is None, f"downgrade base 后 alembic_version 应无行，实际 {revision!r}"


