def _alembic_config(database_url: str) -> Config:
    cfg = Config(str(ALEMBIC_INI))
    cfg.set_main_option("script_location", str(MIGRATIONS_DIR))
    # 等价于命令行 -x db_url=...；migrations/env.py 用 context.get_x_argument() 读取
    cfg.cmd_opts = Namespace(x=[f"db_url={database_url}"])
    return cfg


@pytest.fixture()
def alembic_cfg(database_url) -> Config:
    return _alembic_config(database_url)


def _drop_schema(engine) -> None:
    with engine.begin() as conn:
        conn.execute(text("DROP SCHEMA IF EXISTS public CASCADE"))
        conn.execute(text("CREATE SCHEMA public"))
        conn.execute(text("GRANT ALL ON SCHEMA public TO public"))


def _table_names(engine) -> set[str]:
    return set(inspect(engine).get_table_names(schema="public"))


def _business_tables(engine) -> set[str]:
    return {name for name in _table_names(engine) if name != VERSION_TABLE}


def _schema_signature(engine) -> dict[str, list[tuple[str, str, bool]]]:
    """表 → 列签名（列名、类型字符串、是否可空），用于幂等性的逐项比较。"""
    inspector = inspect(engine)
    signature: dict[str, list[tuple[str, str, bool]]] = {}
    for table in sorted(inspector.get_table_names(schema="public")):
        columns = inspector.get_columns(table, schema="public")
        signature[table] = sorted(
            (col["name"], str(col["type"]), bool(col["nullable"])) for col in columns
        )
    return signature


