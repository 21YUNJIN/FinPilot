"""Alembic 迁移链集成测试（V5 DATA-04、NFR-02、SYS-04）。

跑在**真实 PostgreSQL** 上（``TEST_DATABASE_URL``，本工作包用 ``finpilot_dev_deploy``），
不使用 SQLite 替代；不使用 ``Base.metadata.create_all`` 建表——本文件考的就是迁移链本身。

覆盖的验收口径
--------------
1. ``alembic upgrade head`` 在**空 schema** 上建出 47 张表，且表集合与
   ``finpilot.models.Base.metadata`` **完全相等**（多一张、少一张都失败）；
2. ``upgrade → downgrade base → upgrade`` 幂等：回滚后只剩 ``alembic_version``，
   再次升级得到与第一次**逐字节相同**的表/索引集合；
3. ``alembic check`` / ``compare_metadata`` 与 models.py **无差异**（关键断言）；
4. 关键唯一约束真实存在且真实生效（``uq_operation_owner``、``uq_grant_use_operation``、
   ``uq_daily_limit_bucket``、``uq_ledger_tx_operation_kind``）；
5. CLI 路径（README/部署文档里写的那条命令）在子进程里同样可跑通。

隔离说明：本模块**覆盖** ``tests/conftest.py`` 的 ``clean_db`` / ``engine`` 夹具——
conftest 的 ``engine`` 会 ``create_all``/``drop_all``，那会掩盖迁移链的真实行为。
每个用例自己在 ``public`` schema 上 drop/create，结束时再 ``upgrade head`` 复原，
因此不会把库留在半迁移状态。

运行（仓库根目录）::

    $env:TEST_DATABASE_URL="postgresql+psycopg://finpilot:finpilot_dev_pw@127.0.0.1:55432/finpilot_dev_deploy"
    & ".\\venv\\Scripts\\python.exe" -m pytest tests/integration/test_migrations.py -q
"""

